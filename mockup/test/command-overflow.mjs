import assert from 'node:assert/strict';
import {chromium} from '@playwright/test';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:5173/');
await page.getByRole('heading',{name:'Documents',exact:true}).waitFor();
const toolbar=page.getByRole('toolbar',{name:'Document commands',exact:true});
assert.equal(await toolbar.locator('button:not(.fui-Button)').count(),0);
await page.setViewportSize({width:320,height:1000});
await page.waitForFunction(()=>document.querySelector('[data-overflowing]'));
assert.equal(await toolbar.evaluate(el=>el.scrollHeight>el.clientHeight),false);
await toolbar.getByRole('button',{name:'More commands',exact:true}).click();
await page.getByRole('menuitem',{name:'Search documents',exact:true}).waitFor();
await page.screenshot({path:'screenshots/13-command-overflow.png',fullPage:true,animations:'disabled'});
await page.getByRole('menuitem',{name:'Search documents',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.getByRole('dialog').getByRole('textbox',{name:'Search documents',exact:true}).fill('Pricing');
assert.equal(await page.locator('[data-document-id]').count(),1);
await page.getByRole('button',{name:'Done',exact:true}).click();
await page.setViewportSize({width:1440,height:1050});
await toolbar.getByRole('textbox',{name:'Search documents',exact:true}).fill('');
await page.getByRole('row').filter({hasText:'Master Services Agreement.docx'}).click();
await page.setViewportSize({width:320,height:1000});
await page.waitForFunction(()=>document.querySelector('[data-overflowing]'));
await toolbar.getByRole('button',{name:'More commands',exact:true}).click();
await page.getByRole('menuitem',{name:'Edit details',exact:true}).waitFor();
await page.getByRole('menuitem',{name:'Edit details',exact:true}).click();
await page.getByRole('button',{name:'Close edit details',exact:true}).waitFor();
assert.deepEqual(errors,[]);
console.log('PASS: native ToolbarButton commands, single-row overflow, search from overflow, selected-row edit from overflow, no runtime errors.');
await browser.close();
